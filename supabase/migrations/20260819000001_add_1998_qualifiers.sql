-- (2008・2018の記念大会は北南)。normalize.QUALIFIER_TO_PREF と必ず対応させること。
-- 欠けていると load で該当校の entry が「地方大会未解決」で捨てられ、
-- その校が絡む試合も芋づるで落ちる(1998夏は 4 entry + 13 試合 = 17 件)。
insert into summer_qualifiers (name, prefecture_id, note) values
  ('東埼玉',   11, '記念大会の分割枠(1998年 第80回)'),
  ('西埼玉',   11, '記念大会の分割枠(1998年 第80回)'),
  ('東神奈川', 14, '記念大会の分割枠(1998年 第80回)'),
  ('西神奈川', 14, '記念大会の分割枠(1998年 第80回)')
on conflict (name) do nothing;
